"""Recompile a game's NROs (code it loads at run time with nn::ro) and index them for the runtime.

    gen_nros.py <nro dir> <guest origin> <out dir> [gen.py options, e.g. --simd c]

Each NRO, in file name order, is recompiled by gen.py for its own fixed base, NRO_REGION + i * NRO_SLOT past the guest
origin (runtime/rt.h NRO_BASE / NRO_SLOT: keep them the same), into <out dir>/nro_<name>/. <out dir>/index.c lists
them for runtime/hle/ro.c: the build id nn::ro::LoadModule recognizes an image by, its base, its function table.
"""
import os
import re
import struct
import subprocess
import sys

NRO_REGION = 0x40000000  # past the NSO modules (8 x 64 MB), below the HLE stubs at 0x80000000
NRO_SLOT = 0x400000      # 4 MB each
MAX_NROS = 256           # (runtime/rt.h)


def main():
    src, origin, out, rest = sys.argv[1], int(sys.argv[2], 0), sys.argv[3], sys.argv[4:]
    files = sorted(f for f in os.listdir(src) if f.endswith('.nro'))
    if len(files) > MAX_NROS:
        sys.exit(f'gen_nros.py: {len(files)} NROs, at most {MAX_NROS}')
    gen = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gen.py')
    entries = []
    for i, f in enumerate(files):
        path = os.path.join(src, f)
        with open(path, 'rb') as fh:
            head = fh.read(0x60)
        if head[0x10:0x14] != b'NRO0':
            sys.exit(f'gen_nros.py: {f} is not an NRO')
        size = struct.unpack_from('<I', head, 0x18)[0] + struct.unpack_from('<I', head, 0x38)[0]
        if size > NRO_SLOT:
            sys.exit(f'gen_nros.py: {f} takes {size:#x} bytes, more than a slot ({NRO_SLOT:#x})')
        name = 'nro_' + re.sub(r'\W', '_', f[:-4])
        base = origin + NRO_REGION + i * NRO_SLOT
        subprocess.run([sys.executable, gen, name, path, hex(base), os.path.join(out, name), *rest], check=True)
        entries.append((name, f[:-4], base, head[0x40:0x60]))

    lines = ['// Generated by tools/gen_nros.py from the game files: the NROs nn::ro loads (runtime/hle/ro.c).',
             '#include "gamelib.h"', '']
    lines += [f'extern const uint64_t {n}_fn_addrs[], {n}_fn_count; extern const GuestFn {n}_fn_ptrs[];'
              for n, _, _, _ in entries]
    lines += ['', 'const GameLibNro game_nros[] = {']
    lines += [f'    {{{{"{file}", {n}_fn_addrs, {n}_fn_ptrs, &{n}_fn_count}}, {base:#x}ull, {{{", ".join(map(str, bid))}}}}},'
              for n, file, base, bid in entries]
    lines += ['    {{0}, 0, {0}},  // (the end)', '};', '']
    with open(os.path.join(out, 'index.c'), 'w') as fh:
        fh.write('\n'.join(lines))
    print(f'gen_nros: {len(entries)} NROs', file=sys.stderr)


if __name__ == '__main__':
    main()
